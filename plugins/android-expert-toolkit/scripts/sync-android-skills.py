#!/usr/bin/env python3
"""Vendor a pinned subset of Google's official Android skills
(https://github.com/android/skills, Apache-2.0) into skills/android/.

Usage: scripts/sync-android-skills.py [ref]
  ref  branch, tag or commit to fetch (default: the commit in the lock file,
       or "main" when no lock exists). Pass "main" to upgrade.

Idempotent: each vendored skill dir is replaced wholesale, then the lock
file records the resolved upstream commit and the skill list. Never edit
vendored files by hand; re-run this script instead.
"""
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

REPO = "android/skills"
PLUGIN_ROOT = Path(__file__).resolve().parent.parent
SKILLS_DIR = PLUGIN_ROOT / "skills" / "android"
LOCK = PLUGIN_ROOT / "android-skills.lock"

# App-development skills only. android-cli is deliberately excluded: users
# often install their own android-cli skill and a same-named copy would shadow it.
SKILLS = [
    "navigation-3",
    "navigation-event",
    "edge-to-edge",
    "adaptive",
    "jetpack-compose-performance",
    "migrate-xml-views-to-jetpack-compose",
    "agp-9-upgrade",
    "r8-analyzer",
    "anr-audit-and-fix",
    "android-profiler",
    "testing-setup",
    "android-intent-security",
    "android-permissions-security",
    "glance-appwidget-updates-and-memory",
    "glance-canonical-layouts",
    "ios-to-android",
]


def die(msg):
    print(f"sync-android-skills: {msg}", file=sys.stderr)
    sys.exit(1)


def locked_ref():
    if not LOCK.is_file():
        return ""
    for line in LOCK.read_text(encoding="utf-8").splitlines():
        if line.startswith("commit="):
            return line[len("commit="):]
    return ""


def resolve_sha(ref):
    if re.fullmatch(r"[0-9a-f]{40}", ref):
        return ref
    out = subprocess.run(
        ["git", "ls-remote", f"https://github.com/{REPO}", ref, f"refs/heads/{ref}", f"refs/tags/{ref}"],
        capture_output=True, text=True,
    ).stdout
    sha = out.splitlines()[0].split("\t")[0] if out.strip() else ""
    if not sha:
        die(f"cannot resolve ref '{ref}'")
    return sha


def main():
    ref = (sys.argv[1] if len(sys.argv) > 1 else "") or locked_ref() or "main"
    sha = resolve_sha(ref)

    SKILLS_DIR.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as work_str:
        work = Path(work_str)
        archive = work / "src.tgz"
        url = f"https://codeload.github.com/{REPO}/tar.gz/{sha}"
        try:
            with urllib.request.urlopen(url) as resp, archive.open("wb") as out:
                shutil.copyfileobj(resp, out)
        except OSError as exc:
            die(f"download failed: {exc}")
        src = work / "src"
        src.mkdir()
        with tarfile.open(archive) as tar:
            members = []
            for m in tar.getmembers():
                parts = m.name.split("/", 1)
                if len(parts) < 2 or not parts[1]:
                    continue
                m.name = parts[1]
                members.append(m)
            tar.extractall(src, members=members, filter="tar")

        for name in SKILLS:
            if name == "android-cli":
                die("android-cli must never be vendored")
            matches = [p.parent for p in src.rglob("SKILL.md") if p.is_file() and p.parent.name == name]
            if len(matches) != 1:
                die(f"expected one '{name}' skill upstream, found {len(matches)}")
            dest = SKILLS_DIR / name
            shutil.rmtree(dest, ignore_errors=True)
            shutil.copytree(matches[0], dest, symlinks=True)
            # Upstream frontmatter says "license: Complete terms in LICENSE.txt".
            shutil.copy(src / "LICENSE.txt", dest / "LICENSE.txt")

    lines = [
        "# Generated by scripts/sync-android-skills.py; do not edit.",
        f"repo=https://github.com/{REPO}",
        f"commit={sha}",
        "license=Apache-2.0",
        *[f"skill={name}" for name in SKILLS],
    ]
    LOCK.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"Vendored {len(SKILLS)} skills from {REPO}@{sha}")


if __name__ == "__main__":
    main()
