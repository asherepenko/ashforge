#!/usr/bin/env bash
# Vendor a pinned subset of Google's official Android skills
# (https://github.com/android/skills, Apache-2.0) into skills/.
#
# Usage: scripts/sync-official-skills.sh [ref]
#   ref  branch, tag or commit to fetch (default: the commit in the lock file,
#        or "main" when no lock exists). Pass "main" to upgrade.
#
# Idempotent: each vendored skill dir is replaced wholesale, then the lock
# file records the resolved upstream commit and the skill list. Never edit
# vendored files by hand; re-run this script instead.
set -euo pipefail

REPO="android/skills"
PLUGIN_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SKILLS_DIR="$PLUGIN_ROOT/skills"
LOCK="$PLUGIN_ROOT/official-skills.lock"

# App-development skills only. android-cli is deliberately excluded: users
# often install their own android-cli skill and a same-named copy would shadow it.
SKILLS=(
  navigation-3
  navigation-event
  edge-to-edge
  adaptive
  jetpack-compose-performance
  migrate-xml-views-to-jetpack-compose
  agp-9-upgrade
  r8-analyzer
  anr-audit-and-fix
  android-profiler
  testing-setup
  android-intent-security
  android-permissions-security
)

locked_ref() {
  [ -f "$LOCK" ] && sed -n 's/^commit=//p' "$LOCK" | head -1
}

ref="${1:-$(locked_ref)}"
ref="${ref:-main}"

# Resolve the ref to a commit SHA so the lock is reproducible.
if [[ "$ref" =~ ^[0-9a-f]{40}$ ]]; then
  sha="$ref"
else
  sha="$(git ls-remote "https://github.com/$REPO" "$ref" "refs/heads/$ref" "refs/tags/$ref" | head -1 | cut -f1)"
  [ -n "$sha" ] || { echo "sync-official-skills: cannot resolve ref '$ref'" >&2; exit 1; }
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
curl -fsSL "https://codeload.github.com/$REPO/tar.gz/$sha" -o "$work/src.tgz"
mkdir "$work/src"
tar -xzf "$work/src.tgz" -C "$work/src" --strip-components=1

for name in "${SKILLS[@]}"; do
  [ "$name" != "android-cli" ] || { echo "sync-official-skills: android-cli must never be vendored" >&2; exit 1; }
  matches=()
  while IFS= read -r skill_md; do matches+=("$(dirname "$skill_md")"); done \
    < <(find "$work/src" -type f -path "*/$name/SKILL.md")
  [ "${#matches[@]}" -eq 1 ] || { echo "sync-official-skills: expected one '$name' skill upstream, found ${#matches[@]}" >&2; exit 1; }
  rm -rf "${SKILLS_DIR:?}/$name"
  cp -R "${matches[0]}" "$SKILLS_DIR/$name"
  # Upstream frontmatter says "license: Complete terms in LICENSE.txt".
  cp "$work/src/LICENSE.txt" "$SKILLS_DIR/$name/LICENSE.txt"
done

{
  echo "# Generated by scripts/sync-official-skills.sh; do not edit."
  echo "repo=https://github.com/$REPO"
  echo "commit=$sha"
  echo "license=Apache-2.0"
  for name in "${SKILLS[@]}"; do echo "skill=$name"; done
} > "$LOCK"

echo "Vendored ${#SKILLS[@]} skills from $REPO@$sha"
