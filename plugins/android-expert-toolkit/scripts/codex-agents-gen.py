#!/usr/bin/env python3
"""Generate Codex custom-agent TOML files from agents/<name>.md.

Codex loads custom agents from TOML (name, description, developer_instructions),
not from Claude's Markdown agents. This writes codex-agents/<name>.toml with the
same body plus a short Codex adapter. Model is left unset so the agent inherits
the session's configured model.

Usage: codex-agents-gen.py --write | --check
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "agents"
OUT = ROOT / "codex-agents"

ADAPTER = """

## Codex runtime adapter

- `${CLAUDE_PLUGIN_ROOT}` in this contract means this plugin's root directory
  (the directory holding `references/` and `skills/`). On Codex it is exposed as
  `${PLUGIN_ROOT}` when set; otherwise resolve it from the plugin cache.
- "Load the `<name>` skill" means read `skills/<name>/SKILL.md` under the plugin
  root (or the installed skill of that name) and follow it.
- Read/Glob/Grep map to native file and shell tools; Write/Edit map to native file
  editing; Bash maps to native command execution. These are mappings, not extra
  permissions: inherit the session's approvals and sandbox.
"""


def parse(path: Path):
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        raise ValueError(f"{path.name}: expected frontmatter")
    front, body = text[4:].split("\n---\n", 1)
    meta = {}
    for line in front.splitlines():
        m = re.fullmatch(r"([a-z_]+):\s*(.+)", line)
        if not m:
            raise ValueError(f"{path.name}: unsupported frontmatter line: {line!r}")
        key, value = m.groups()
        meta[key] = json.loads(value) if value.startswith('"') else value
    for key in ("name", "description", "tools"):
        if key not in meta:
            raise ValueError(f"{path.name}: missing {key}")
    if meta["name"] != path.stem:
        raise ValueError(f"{path.name}: name must match file name")
    return meta, body.strip()


def render(path: Path) -> str:
    meta, body = parse(path)
    instructions = body + ADAPTER + f"\nCanonical tool scope: {meta['tools']}.\n"
    header = (
        "# Generated by scripts/codex-agents-gen.py; do not edit.\n"
        f"# Source: agents/{path.name}\n"
        f"# Source SHA256: {hashlib.sha256(path.read_bytes()).hexdigest()}\n"
    )
    fields = {
        "name": meta["name"],
        "description": meta["description"],
        "developer_instructions": instructions,
    }
    # JSON basic strings are valid TOML basic strings; keep Unicode literal.
    return header + "".join(f"{k} = {json.dumps(v, ensure_ascii=False)}\n" for k, v in fields.items())


def main() -> int:
    ap = argparse.ArgumentParser()
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args()

    expected = {f"{p.stem}.toml": render(p) for p in sorted(SRC.glob("*.md"))}
    actual = {p.name: p.read_text(encoding="utf-8") for p in OUT.glob("*.toml")} if OUT.exists() else {}

    if args.write:
        OUT.mkdir(exist_ok=True)
        for stale in set(actual) - set(expected):
            (OUT / stale).unlink()
        for name, text in expected.items():
            (OUT / name).write_text(text, encoding="utf-8")
        print(f"wrote {len(expected)} Codex agents to {OUT.relative_to(ROOT)}/")
        return 0

    drift = sorted(n for n in set(expected) | set(actual) if expected.get(n) != actual.get(n))
    if drift:
        print("Codex agents out of date: " + ", ".join(drift), file=sys.stderr)
        print("Run: python3 scripts/codex-agents-gen.py --write", file=sys.stderr)
        return 1
    print(f"{len(expected)} Codex agents up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
